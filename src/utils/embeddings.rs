/// แปลงข้อความเป็นเวกเตอร์ (Embeddings) โดยใช้ LLM หรือโมเดลที่เหมาะสม
pub fn embed_text(text: &str) -> Vec<f32> {
    // ตัวอย่างนี้ใช้เวกเตอร์จากโมเดล pre-trained เช่น OpenAI หรือจากการคำนวณแบบง่ายๆ
    // หากต้องการให้มีการใช้งานจริง สามารถเชื่อมต่อกับโมเดลหรือ API ที่รองรับการคำนวณ embeddings ได้

    // สร้างเวกเตอร์ mock สำหรับตัวอย่างนี้
    let vector: Vec<f32> = text
        .chars()
        .map(|c| c as u8 as f32 / 255.0)  // สร้างเวกเตอร์จากรหัส ASCII ของตัวอักษร
        .collect();

    vector
}
